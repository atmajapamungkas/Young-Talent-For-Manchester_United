def parse_value(val):
    if pd.isna(val): return np.nan
    v = str(val).lower().strip()
    # Hapus simbol mata uang
    v = v.replace('€', '').replace('£', '').replace('$', '').replace(',', '').strip()

    # Coba berbagai format
    try:
        if 'm' in v or 'mio' in v or 'million' in v:
            v = v.replace('m', '').replace('mio', '').replace('million', '').strip()
            return float(v) * 1_000_000
        elif 'k' in v or 'thousand' in v:
            v = v.replace('k', '').replace('thousand', '').strip()
            return float(v) * 1_000
        elif 'bn' in v or 'billion' in v:
            v = v.replace('bn', '').replace('billion', '').strip()
            return float(v) * 1_000_000_000
        else:
            # Mungkin sudah dalam angka murni (EUR)
            return float(v)
    except:
        return np.nan

