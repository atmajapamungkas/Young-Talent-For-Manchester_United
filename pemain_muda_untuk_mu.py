def score_pool(pool):
    if len(pool) == 0: return pd.DataFrame()

    res = pool[[col_name, col_club, 'position_short', 'age_clean']].copy()
    if col_nation: res['nationality'] = pool[col_nation]
    if col_value: res['market_value_str'] = pool[col_value]
    res['market_value_eur'] = pool['market_value_eur']

    # 1. Age Score: Lebih muda = skor lebih tinggi (17 thn = 100, 23 thn = 40)
    res['age_score'] = (100 - (res['age_clean'] - 17) * 10).clip(0, 100)

    # 2. Value Efficiency: Market value lebih rendah = skor lebih tinggi (undervalued)
    valid_vals = res['market_value_eur'].dropna()
    if len(valid_vals) > 10:
        res['value_rank_pct'] = res['market_value_eur'].rank(pct=True, ascending=True)
        res['value_score'] = (1 - res['value_rank_pct']) * 100
    else:
        res['value_score'] = 50

    # 3. Composite Score: 40% Umur (investasi jangka panjang) + 60% Value Efficiency (murah tapi potensial)
    res['composite_score'] = (0.4 * res['age_score'] + 0.6 * res['value_score']).round(2)

    return res.sort_values('composite_score', ascending=False).head(10)

