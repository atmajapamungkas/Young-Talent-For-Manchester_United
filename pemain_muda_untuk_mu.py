    df_ml = pd.concat([df_ml, pos_dummies], axis=1)
    features += pos_dummies.columns.tolist()

    print(f"📊 Total fitur clustering: {len(features)}")

    # Siapkan data (handle NaN)
    X_data = df_ml[features].copy()
    X_data = X_data.fillna(X_data.median())  # Imputasi NaN dengan median

    # Validasi akhir
    if len(X_data) < 10:
        raise ValueError(f"❌ Data terlalu sedikit setelah preprocessing: {len(X_data)}")

    # Standardisasi
    scaler = StandardScaler()
    X = scaler.fit_transform(X_data)

    # Cari K optimal
    sil_scores = []
    max_k = min(10, len(df_ml) // 5)
    K_range = range(3, max(4, max_k))

    print(f"\n🔍 Mencari K optimal (range: {list(K_range)})...")
    for k in K_range:
        km = KMeans(n_clusters=k, random_state=42, n_init=10)
        labels = km.fit_predict(X)
        sil_scores.append(silhouette_score(X, labels))

    best_k = list(K_range)[np.argmax(sil_scores)]
    print(f"✓ K optimal: {best_k} (silhouette: {max(sil_scores):.3f})")

    # Fit model final
    km_final = KMeans(n_clusters=best_k, random_state=42, n_init=10)
    df_ml['cluster'] = km_final.fit_predict(X)

    # Cari cluster "Hidden Gem": Umur muda + Value rendah
    cluster_stats = df_ml.groupby('cluster').agg({'age_clean': 'mean'}).reset_index()
